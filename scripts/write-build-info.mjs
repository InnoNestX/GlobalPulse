import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(root, "src/build-info.generated.ts");

function readGit(args) {
  try {
    return execSync(`git ${args}`, {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return "";
  }
}

function readEnv(...keys) {
  for (const key of keys) {
    const value = process.env[key]?.trim();
    if (value) return value;
  }
  return "";
}

const commitSha = readEnv("WORKERS_CI_COMMIT_SHA", "GITHUB_SHA", "CF_PAGES_COMMIT_SHA") || readGit("rev-parse HEAD");
const branch = readEnv("WORKERS_CI_BRANCH", "GITHUB_REF_NAME", "CF_PAGES_BRANCH") || readGit("branch --show-current");
const buildId = readEnv("WORKERS_CI_BUILD_UUID", "GITHUB_RUN_ID", "CF_PAGES_URL");
const buildTime = new Date().toISOString();

const source = [
  "/* This file is generated by scripts/write-build-info.mjs. */",
  "export const BUILD_INFO = {",
  `  commitSha: ${JSON.stringify(commitSha || undefined)},`,
  `  branch: ${JSON.stringify(branch || undefined)},`,
  `  buildId: ${JSON.stringify(buildId || undefined)},`,
  `  buildTime: ${JSON.stringify(buildTime)},`,
  "} as const;",
  "",
].join("\n");

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, source);
console.log(`Wrote ${outputPath}`);
